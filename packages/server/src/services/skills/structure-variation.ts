/**
 * PR-X1: 结构组合引擎 — 把"4 个死模板"变成组合空间。
 * 每次生成随机抽: 标题公式 × 开头钩子 × 结尾CTA × 口播脚本风格, 拼成 prompt 后缀。
 * 与模板(骨架)和人设(账号声音)正交: 模板管结构, 人设管语气, 这里管"这一篇的变化"。
 */

const TITLE_FORMULAS = [
  "数字冲击式: 用具体数字开头制造冲击 (如「录用率58%的...」)",
  "疑问悬念式: 用一个目标读者最关心的问题作标题",
  "对比反差式: 用「看起来A, 实际上B」的反差结构",
  "避坑警告式: 「投稿前必须知道的...」「别再...」",
  "结果导向式: 直接承诺读者收益 (「读完这篇你就知道...」)",
  "盘点清单式: 「N个/N本/N条」清单型标题",
  "时效紧迫式: 结合时间节点 (「2026年还能...」「最后窗口期」)",
  "身份代入式: 直接点名目标人群 (「赶毕业的你...」「普通课题组...」)",
  "反常识式: 挑战普遍认知 (「IF高不等于好投」)",
  "经验自述式: 「过来人」口吻 (「投了3次才明白...」)",
];

const HOOK_STYLES = [
  "悬念钩子: 开头抛出一个反直觉的事实或数据, 不立即解释",
  "痛点钩子: 第一句直击目标读者当下最焦虑的场景",
  "故事钩子: 用一个具体的(可虚构但真实感强的)投稿小故事开场",
  "数据钩子: 开头连续甩2-3个硬数据建立专业感",
  "提问钩子: 连续两个问题逼读者自我代入",
  "吐槽钩子: 轻吐槽行业现象, 拉近距离再转正题",
  "结论先行钩子: 第一段直接给结论, 后文论证",
  "场景钩子: 描绘一个读者熟悉的具体场景(深夜改稿/导师催稿)",
];

const CTA_STYLES = [
  "关注引导: 自然提示关注获取后续同类内容",
  "收藏引导: 强调本文信息密度值得收藏备用",
  "互动提问: 结尾抛一个具体问题引导评论区讨论",
  "下期预告: 预告下一篇相关主题制造期待",
  "私信/留言引导: 邀请读者说出自己的目标期刊/困惑",
  "转发引导: 提示转给「正在投稿的同门/同事」",
  "工具引导: 提示通过主页/菜单获取选刊工具或资料",
  "无CTA: 这一篇不加行动号召, 以干货收尾保持克制",
];

const SCRIPT_STYLES = [
  "钩子型口播: 前5秒必须有一个让人停下滑动的钩子句",
  "盘点型口播: 「三个数字带你看懂这本刊」式结构",
  "问答型口播: 自问自答, 每个问题都是读者想问的",
  "反常识型口播: 以「很多人以为...其实...」展开",
  "经验分享型口播: 第一人称过来人口吻, 口语化强",
];

function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)]!;
}

/** 每次生成调用一次 — 随机组合, 同参数也次次不同 */
export function buildVariationSuffix(): string {
  return `

【本篇结构变化指令 (PR-X1 防同质化, 必须遵守)】
- 标题采用「${pick(TITLE_FORMULAS)}」
- 开头采用「${pick(HOOK_STYLES)}」— 严禁使用与近期文章雷同的开头套路
- 结尾采用「${pick(CTA_STYLES)}」
- videoScript 采用「${pick(SCRIPT_STYLES)}」
- 段落节奏在模板基础上做自然变化, 不要每篇都是同样的小标题措辞`;
}

/** 账号人设 + 风格画像 → prompt 块 (没有则返回空串) */
export function buildPersonaSuffix(persona?: string | null, styleProfile?: string | null): string {
  if (!persona && !styleProfile) return "";
  let out = "\n\n【账号人设 (本文以此身份写作, 优先级高于模板默认语气)】";
  if (persona) out += `\n${persona.trim().slice(0, 800)}`;
  if (styleProfile) out += `\n\n【账号风格画像 (从该账号范文提炼, 模仿其行文风格)】\n${styleProfile.trim().slice(0, 1200)}`;
  return out;
}

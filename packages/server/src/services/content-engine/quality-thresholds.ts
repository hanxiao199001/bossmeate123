//
//   ▎ 六维评的是「对读者有没有价值」，不是「有没有某类元素」。
//   ▎
//   ▎ 任何一维的判据里，不得出现绑定特定体裁的词
//   ▎ （投稿建议 / 审稿流程 / 选刊痛点 ...）。
//   ▎
//   ▎ 判据一旦锚在元素上，新体裁就不是"得分低"，是"按定义拿不到分" ——
//   ▎ 而这件事在数据上看起来和"写得差"一模一样。
//
// ── 第一个案例：practicality（8-21 实测） ──
//
// 判据原文（v2）：
//   「5. 实用性（权重10%）：8分 = 读完能直接用（投稿建议具体可操作，
//     落到"谁该投/怎么投/避什么坑"）」
//
// 「实用」的唯一定义就是**投稿建议**，举的三个例子全是投稿动作。
// A2 新体裁「学科定位」明令禁写投稿指南 → 它在这一维天然拿不到分，
// **与内容是否实用毫无关系**。实测 5.22 → 3.22。
//
// 同族第二例：topicHook 判据写「直戳**投稿/选刊**痛点」+「平铺直叙介绍背景 ≤5分」，
// 而新体裁的设计就是陈述句开场 —— 按设计撞上一条 ≤5 的硬天花板。实测 7.56 → 4.22。
//
// ── 与 originalityCompliance 那次是同一个病 ──
//
// 8-20 查出：那一维名字承诺「合规审查」，判据原文只有一句
// 「无违禁词、不像搬运、无 AI 腔套话堆砌」—— 三条软性风格判断之一。
// **在拿一个维度的分做任何决策之前，先读它的判据原文。**
// 名字不是保证；分数低不等于内容差，可能只是尺子只认一种写法。
//
// ── 改判据的程序 ──
//
// 1. 先读原文，判断低分是"内容问题"还是"尺子问题"（两者的处置完全相反）
// 2. 一次只改一件，独立部署 —— 混着改就分不清是哪个改动起的作用
// 3. 预注册验收判据（`scoring-rubric-experiment.ts`），基线先跑
// 4. 版本号 +1（`SIX_DIM_SCORING_VERSION`），否则新旧分静默混一列
// 5. 尺子放宽 → **发布线必须重新校准**：分数整体上移不是内容变好了。
//    改前先算旧线对应什么分位，改后要么挪到同分位，要么明确决定放宽到 X%
//    并把理由写进 `runtime-params` 的 evidence 字段

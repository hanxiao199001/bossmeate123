/**
 * Agent 自动放行线。
 * - 语义: 六维总分达到此值 **且** 其余检查全过 → 自动 approved, 不经人工。
 * - 环节: QualityChecker Agent 的 decide()。
 * - 为什么是 85(高于发布线 80): 自动放行等于放弃人工兜底, 门槛必须严于"人工复核后可发"。
 * - ⚠️ 未评上分(totalScore === null)时**绝不自动放行** —— 未评分不是高分也不是低分, 一律转人工。
 *   这是 7-27 事故("没评上分"被当成"评了 0 分")在裁决侧的同一条教训。
 */
export const AGENT_AUTO_APPROVE_SCORE = 85;

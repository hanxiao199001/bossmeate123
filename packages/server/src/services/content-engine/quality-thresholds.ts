/**
 * 质量分数线 —— **全系统唯一真相源**(纯常量, 零 IO 零依赖)。
 *
 * ## 病根
 * 架构审计查出全系统有 6 套分数线散落各处, 都是裸字面量:
 *   quality-check-v2 的 80/6, quality-check-engine 的 70, crawl-data-sink 的 70,
 *   article-skill 的 70, quality-checker 的 85 + env.QUALITY_MIN_SCORE, content-worker 的动态阈值。
 * 光看代码根本分不清「这个 70 和那个 70 是不是一回事」—— 事实上不是:
 * 有的是六维总分、有的是四维总分、有的是知识库沉淀门槛、有的是发布门槛。
 * 数字撞在一起纯属巧合, 而巧合会让人误以为改一个就改全了。
 *
 * ## 本表的规矩
 * 1. 每条必须写清 **语义 / 适用环节 / 为什么是这个数**。只有数字没有语义的条目不许进。
 * 2. 消费方一律 import, 不许再写字面量。
 * 3. 数值本身**不是**随便改的 —— 它决定什么内容能发出去。改前先看"为什么是这个数"。
 *
 * ⚠️ 收口进度: 本表目前收了六维体系 + Agent 自动放行线。
 *    仍待收口(散在各自文件里, 见架构修复设计框架 阶段1 清单):
 *      - `data-collection/quality-check-engine.ts` 的四维总分 70 与评级 80/70
 *      - `data-collection/crawl-data-sink.ts` 的 MIN_QUALITY_SCORE = 70
 *      - `skills/article-skill.ts:391` 的 >= 70
 *      - `content-engine/content-worker.ts` 的动态 threshold
 *    这几处语义与六维体系不同(采集质检 / 知识库沉淀 / 生成自检), 收口时必须分别命名, 别并成一个数。
 */


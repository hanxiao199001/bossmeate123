/**
 * 六维总分发布线。
 * - 语义: 六个维度加权总分, 达到即"可进可发池"(仍需过编造/合规/出稿健康等硬闸)。
 * - 环节: `sixDimQualityCheck` 判 passed; 反馈文案里的"X 分发布线"也用它。
 * - 为什么是 80: 老韩人工采用/驳回校准出的线, 详见 `内容质量评分标准-80分线.md`。
 *   低于此线的稿子人工复核时驳回率显著上升, 是经验值不是拍脑袋。
 */
/**
 * 🔴 六维评分标尺版本号。**改评分 prompt 必须同时 +1**（老韩 8-21 立）。
 *
 * ## 为什么必须有
 *
 * 8-21 决定给六维判据动刀（解除双重计分 / practicality 体裁中立化 /
 * topicHook 去硬上限 / structureDensity 补中间档）。改完之后：
 *
 * ```
 * quality_verdict 已打的标   = 旧尺子
 * 周报的 15% 达标率           = 旧尺子
 * 8-20 那张 328 篇的维度表    = 旧尺子
 * 明天起的所有分              = 新尺子
 * ```
 *
 * 不带版本号，一周后没人分得清哪个分是哪把尺子打的 ——
 * **这是红线 #20 最经典的形态，而且这次是我们主动制造的。**
 *
 * ## 规矩
 *
 * 1. 任何一次评分 prompt 文字改动（判据措辞、档位、权重、加减维度）→ 版本 +1。
 *    prompt 之外的改动（重试策略、超时、模型路由）**不**动版本 —— 那不改变尺子。
 * 2. 落库：`metadata.sixDimScoringVersion` + `content_publish_log.scoring_version`。
 * 3. **跨版本趋势对比一律禁止**，除非显式标注两侧版本。
 *    「本周达标率比上周高」在跨版本时是无意义的句子。
 * 4. 存量无此字段的行 = v2 之前，按 `SCORING_VERSION_LEGACY` 处理。
 *
 * ## 版本史
 *
 * - `v2` —— 8-21 之前的既有尺子（历史上没打过版本号，回填时按 legacy 处理，
 *           但语义上就是它）。已知偏见：judged 的是「像不像一篇投稿指南」——
 *           practicality 判据只认投稿建议、topicHook 痛点绑投稿且惩罚陈述句开场、
 *           structureDensity 与 dataAccuracy 双重计分（合计权重 45%）。
 * - `v3` —— 8-21 件1：**解除 structureDensity × dataAccuracy 的双重计分**。
 *
 *   🔴 **件 1 基于逻辑保留，未获实验支持。**
 *   实测（8-22，冻结样本 n=30，v2→v3 同批对照）：
 *     · 方向信号 rich 组 structureDensity 8↑/0↓/4=，是整张表唯一干净的方向
 *     · 幅度全部落在噪音带内（单维噪音 ±1.3，本次最大差值 1.33）
 *     · corr(structureDensity, dataAccuracy) **反向**：0.35 → 0.41，未下降
 *   **不得引用本次实验作为「双重计分已修复」的证据。**
 *   保留的理由是逻辑本身：一个原因不该被记两次，这不需要实验证明；
 *   要把 1.0 的效应从 ±1.3 的噪音里测出来，n=9 差得远，重跑成本远超收益。
 *   「改动方向对但证明不了」是个诚实的状态，比硬凑一个「验证通过」强。

 *           `structureDensity` 判据里的「干货密」与 `dataAccuracy` 的
 *           「每 200 字至少 1 个具体硬数据」是同一件事，合计权重 45%——
 *           sparse 刊没数据被同一个原因扣两遍，这直接解释了 sparse 组达标率 1.4%。
 *           v3 只改一句：本维改为「只看组织方式，不看有没有硬数据」。
 *           ⚠️ 件2(practicality 中立化) / 件3(topicHook 去硬上限) / 件4(结构补中间档)
 *           **各自独立部署并各自 +1 版本** —— 混着改就分不清是哪个改动起的作用。
 */
export const SIX_DIM_SCORING_VERSION = "v3";


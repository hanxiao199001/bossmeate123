/**
 * 六维总分发布线。
 * - 语义: 六个维度加权总分, 达到即"可进可发池"(仍需过编造/合规/出稿健康等硬闸)。
 * - 环节: `sixDimQualityCheck` 判 passed; 反馈文案里的"X 分发布线"也用它。
 * - 为什么是 80: 老韩人工采用/驳回校准出的线, 详见 `内容质量评分标准-80分线.md`。
 *   低于此线的稿子人工复核时驳回率显著上升, 是经验值不是拍脑袋。
 */
export const SIX_DIM_PUBLISH_TOTAL = 80;

/**
 * 六维单维最低分。
 * - 语义: 任一维度低于此值即不通过, 即使总分够 —— 防"五项优秀掩盖一项致命"。
 * - 环节: 与 SIX_DIM_PUBLISH_TOTAL 一起构成 passed 判据(总分够 **且** 每维够)。
 * - 为什么是 6: 满分 10 分制下 6 分是"勉强及格", 再低说明该维度实质缺失(如全文零数据支撑)。
 */
export const SIX_DIM_PUBLISH_MIN_DIM = 6;

/**
 * 六维"优秀"线(仅用于反馈文案措辞, 不参与放行判定)。
 * - 语义: 给运营看的评价词, 高于此分显示"内容质量优秀"。
 * - 环节: `summarizeSixDim` 之类的文案生成。
 * - 为什么是 90: 纯展示分档, 与发布无关; 改它只影响措辞不影响什么能发。
 */
export const SIX_DIM_EXCELLENT_SCORE = 90;

/**
 * 低分维度提示线(反馈文案里"低分维度"列出哪些)。
 * - 语义: 低于此分的维度会被逐个列出并给修改建议。
 * - 为什么是 8: 比及格线 6 高, 因为这是"值得再抬一抬"的提醒而非"不合格"判定。
 */
export const SIX_DIM_WEAK_DIM_HINT = 8;

// ─────────────────────────────────────────────────────────────
